import { getErrorMessage } from '../../utils/utils';
import { kotlinWasmBaseUrl } from '../../vendors';

// Runs in the result page when `customSettings.kotlin.target` is `wasm`.
//
// The compiler emits four interdependent files. The page cannot serve sibling
// modules, so the compiler hands them over as one JSON payload in a typed script
// tag and this script rebuilds them as Blob modules, rewriting each specifier to
// the Blob URL that replaces it. `main.mjs` instantiates the module and calls
// `_start()` on import, so importing it runs the program.
//
// Console output needs no work: Kotlin/Wasm's `println` calls the page's
// `console.log`, which LiveCodes already captures.

const SCRIPT_TYPE = 'text/kotlin-wasm';

interface EmittedFile {
  name: string;
  content: string;
  encoding: 'utf8' | 'base64';
}

interface KotlinWasmApi {
  ready: boolean;
  failed: boolean;
  input: string;
  output: string | null;
  error: string | null;
  exitCode: number | null;
  loaded: Promise<void>;
  /** Set before the first run, or passed to `run` for later runs. */
  stdinHook: string;
  run: (
    input?: string,
  ) => Promise<{ output: string | null; error: string | null; exitCode: number | null }>;
}

declare const window: Window & {
  livecodes: Record<string, any>;
  console: Console;
};

/**
 * The hook the package's compile-time prelude calls to read a line.
 *
 * Kotlin/Wasm's `readlnOrNull` returns null and `readLine` is unresolved, so the
 * package injects a prelude when input is supplied. The name must match
 * `JS_STDIN_HOOK` in `src/prelude.js` of `@live-codes/kotlin-wasm` exactly,
 * including case — that is what makes it work.
 */
const STDIN_HOOK = '__liveCodesKotlinWasmReadLine';

const decodeBase64 = (content: string): Uint8Array => {
  const binary = atob(content);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return bytes;
};

const bytesOf = (file: EmittedFile): Uint8Array =>
  file.encoding === 'base64' ? decodeBase64(file.content) : new TextEncoder().encode(file.content);

const textOf = (file: EmittedFile): string =>
  file.encoding === 'base64' ? new TextDecoder().decode(decodeBase64(file.content)) : file.content;

/** Every typed script's payload, merged, so a reload-safe re-run sees all parts. */
const readPayload = (): EmittedFile[] => {
  const files: EmittedFile[] = [];
  document.querySelectorAll(`script[type="${SCRIPT_TYPE}"]`).forEach((script) => {
    const text = script.textContent?.trim();
    if (!text) return;
    try {
      const parsed = JSON.parse(text);
      if (Array.isArray(parsed)) files.push(...parsed);
    } catch {
      // A malformed payload is reported by the run, which then has no files.
    }
  });
  return files;
};

const findFile = (files: EmittedFile[], name: string) => files.find((file) => file.name === name);

/**
 * Rebuilds the module graph as Blob URLs and imports it.
 *
 * The specifiers are matched as text because they are generated by the Kotlin
 * compiler, not by us. If either replacement stops matching, importing would fail
 * with an unresolvable URL, so that is checked explicitly and reported as a clear
 * error instead of a cryptic module-resolution failure.
 */
const runWasmProgram = async (files: EmittedFile[]): Promise<void> => {
  const wasm = findFile(files, 'main.wasm');
  const builtins = findFile(files, 'main.js-builtins.mjs');
  const importObject = findFile(files, 'main.import-object.mjs');
  const main = findFile(files, 'main.mjs');
  if (!wasm || !builtins || !importObject || !main) {
    throw new Error('The compiled Kotlin/Wasm output is incomplete; try compiling again.');
  }

  const urls: string[] = [];
  const blob = (content: BlobPart, type: string) => {
    const url = URL.createObjectURL(new Blob([content], { type }));
    urls.push(url);
    return url;
  };

  try {
    const wasmUrl = blob(bytesOf(wasm), 'application/wasm');
    const builtinsUrl = blob(textOf(builtins), 'text/javascript');

    const importObjectUrl = blob(
      textOf(importObject).replaceAll("'./main.js-builtins.mjs'", `'${builtinsUrl}'`),
      'text/javascript',
    );

    const mainText = textOf(main)
      .replaceAll("'./main.import-object.mjs'", `'${importObjectUrl}'`)
      .replaceAll("new URL('./main.wasm',import.meta.url).href", `'${wasmUrl}'`);
    if (!mainText.includes(`'${wasmUrl}'`) || !mainText.includes(`'${importObjectUrl}'`)) {
      throw new Error('The Kotlin/Wasm output has an unexpected shape; try compiling again.');
    }
    const mainUrl = blob(mainText, 'text/javascript');

    // Importing runs the program: `main.mjs` calls `_start()` at its top level.
    await import(/* webpackIgnore: true */ mainUrl);
  } finally {
    for (const url of urls) URL.revokeObjectURL(url);
  }
};

window.livecodes ??= {} as any;
const kotlin = (window.livecodes.kotlin ??= {} as KotlinWasmApi);

kotlin.ready = false;
kotlin.failed = false;
// Defined up front so markup can assign the input before the first run, as the
// other wasm languages' `livecodes.<lang>.input` allows.
kotlin.input = '';
kotlin.output = null;
kotlin.error = null;
kotlin.exitCode = null;
kotlin.stdinHook = STDIN_HOOK;

/** Supplies the prelude's line reader: pre-supplied lines, not an interactive console. */
const installStdin = (input: string) => {
  const lines = input ? String(input).replace(/\r\n?/g, '\n').split('\n') : [];
  if (lines.length && lines[lines.length - 1] === '') lines.pop();
  let index = 0;
  (window as any)[STDIN_HOOK] = () => (index < lines.length ? lines[index++] : null);
};

/**
 * Records what the program prints while it runs.
 *
 * Kotlin/Wasm reaches JavaScript for output through hooks the compiler generates
 * in `main.import-object.mjs` — `kotlin.io.printlnImpl` and `printImpl` both end
 * in `console.log`. So capturing means observing `console` for the duration of
 * the run.
 *
 * The whole `window.console` value is swapped, rather than assigning to its
 * methods: LiveCodes replaces `console` with a Proxy whose `set` would land on
 * the real console, and whose `get` would then hand back the wrapper, recursing
 * on the next call. Swapping the property leaves that Proxy untouched, and the
 * replacement delegates to it, so output still reaches the app's console.
 *
 * Returns a function that stops capturing and yields the collected text.
 */
const captureOutput = () => {
  const original = window.console;
  const printed: string[] = [];

  const capturing = new Proxy(original, {
    get(target, property, receiver) {
      if (property === 'log' || property === 'info' || property === 'debug') {
        return (...args: unknown[]) => {
          printed.push(args.map(String).join(' '));
          (target[property] as (...a: unknown[]) => void).apply(target, args);
        };
      }
      return Reflect.get(target, property, receiver);
    },
  });

  window.console = capturing;

  return () => {
    window.console = original;
    return printed.length ? printed.join('\n') : null;
  };
};

kotlin.run = async (input?: string) => {
  const stdin = `${input ?? kotlin.input ?? ''}`;
  kotlin.input = stdin;
  installStdin(stdin);

  const files = readPayload();
  if (!files.length) {
    // The compiler returns '' for an empty program, so there is nothing to run.
    kotlin.ready = true;
    kotlin.output = null;
    kotlin.error = null;
    kotlin.exitCode = 0;
    return { output: null, error: null, exitCode: 0 };
  }

  const stopCapturing = captureOutput();
  let output: string | null = null;
  try {
    await runWasmProgram(files);
    output = stopCapturing();
    kotlin.output = output;
    kotlin.error = null;
    kotlin.exitCode = 0;
    kotlin.ready = true;
    return { output, error: null, exitCode: 0 };
  } catch (error) {
    output = stopCapturing();
    const message = 'Error: ' + getErrorMessage(error);
    kotlin.output = output;
    kotlin.error = message;
    kotlin.exitCode = 1;
    kotlin.ready = true;
    // eslint-disable-next-line no-console
    console.error(message);
    return { output, error: message, exitCode: 1 };
  }
};

kotlin.loaded = new Promise<void>((resolve, reject) => {
  const interval = setInterval(() => {
    if (kotlin.failed) {
      clearInterval(interval);
      reject(new Error(kotlin.error || 'Failed to load the Kotlin/Wasm runtime'));
    } else if (kotlin.ready) {
      clearInterval(interval);
      resolve();
    }
  }, 50);
});

window.addEventListener('load', async () => {
  parent.postMessage({ type: 'loading', payload: true }, '*');
  await kotlin.run(kotlin.input);
  parent.postMessage({ type: 'loading', payload: false }, '*');
});

