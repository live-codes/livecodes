// @ts-nocheck -- vendored fixed Popcorn worker runtime (plain JS, typed as text import)
/*
 * Persistent Popcorn worker runtime for LiveCodes Elixir (Wasm).
 *
 * Based on the iframe runtime shipped with
 * `live-codes/elixir-browser-eval` (itself from Software Mansion Popcorn).
 * The runtime is hosted in a Worker owned by the result window, not in an
 * iframe owned by the result document. `document.open()/write()/close()` used
 * by LiveReload replaces the document but keeps the window (and therefore this
 * worker) alive, so a code edit no longer reboots the VM.
 *
 * Changes from the upstream iframe runtime:
 *
 * 1. `BUNDLE_PATH` is injected by the main thread when the Blob worker is
 *    created, so the runtime does not depend on a DOM meta element.
 * 2. Messages go through `self` instead of `window.parent`. The main thread
 *    owns the Worker object, so no cross-origin relay is required.
 * 3. Emscripten pthread workers are created from a Blob URL
 *    (`mainScriptUrlOrBlob`) because a module worker must be same-origin and
 *    the CDN mirror is cross-origin.
 * 4. The Elixir boot code generated by the pinned bundle expects
 *    `window.parent.document` in its JS interop. A minimal shim is installed
 *    immediately before `init()`; it is deliberately installed after the
 *    AtomVM module is imported so Emscripten still detects a worker
 *    environment.
 *
 * Message protocol (postMessage types) is unchanged from upstream, with an
 * extra `popcorn-timing` diagnostic channel used by the benchmarks/tests.
 */

const MESSAGES = {
  INIT: 'popcorn-init',
  START_VM: 'popcorn-startVm',
  CALL: 'popcorn-call',
  CAST: 'popcorn-cast',
  CALL_ACK: 'popcorn-callAck',
  STDOUT: 'popcorn-stdout',
  STDERR: 'popcorn-stderr',
  HEARTBEAT: 'popcorn-heartbeat',
  RELOAD: 'popcorn-reload',
  TIMING: 'popcorn-timing',
  FATAL: 'popcorn-fatal',
};

const BUNDLE_PATH = '__LIVECODES_ELIXIR_BUNDLE_URL__';

const HEARTBEAT_INTERVAL_MS = 500;

let Module = null;
let binaryDir = '';
let workerScript = '';

const mark = (name, detail) => {
  send(MESSAGES.TIMING, { name, at: performance.now(), detail });
};
mark('worker-start');

// The binaries sit next to the bundle, which may be a CDN mirror.
const locateBinary = (path) => {
  send(MESSAGES.STDERR, `locateFile: ${path} -> ${binaryDir + path}\n`);
  return binaryDir + path;
};

class TrackedValue {
  // eslint-disable-next-line @typescript-eslint/explicit-member-accessibility -- plain JS file, no TS modifiers
  constructor({ key, value }) {
    if (typeof key !== 'number') {
      throw new Error('key property in TrackedValue must be a number');
    }
    this.key = key;
    this.value = value;
  }
}

globalThis.TrackedValue = TrackedValue;

async function runWorker() {
  try {
    await startPopcorn();
  } catch (error) {
    // A worker that dies silently is near-impossible to debug — report it and
    // let the main thread reject the boot waiters immediately instead of
    // waiting for the init timeout.
    const detail = (error && (error.stack || error.message)) || String(error);
    send(MESSAGES.STDERR, `Runtime failed: ${detail}\n`);
    send(MESSAGES.FATAL, { message: detail });
    throw error;
  }
}

async function startPopcorn() {
  const bundlePath = BUNDLE_PATH;
  binaryDir = new URL('.', bundlePath).href;

  // Emscripten spawns its pthread workers from the runtime module's own URL —
  // `new Worker(new URL("AtomVM.mjs", import.meta.url), { type: "module" })` —
  // and a worker script must be same-origin, which would pin the runtime to this
  // origin. It accepts `mainScriptUrlOrBlob` as an override, so the module is
  // fetched from the mirror and handed back as a Blob URL: same-origin, and with
  // a usable base URL.
  mark('atomvm-import-start');
  const source = await fetch(binaryDir + 'AtomVM.mjs').then((resp) => resp.text());
  workerScript = URL.createObjectURL(new Blob([source], { type: 'text/javascript' }));
  const { default: init } = await import(binaryDir + 'AtomVM.mjs');
  mark('atomvm-import-end');
  send(MESSAGES.STDERR, 'AtomVM module imported.\n');

  mark('bundle-fetch-start');
  const bundleBuffer = await fetch(bundlePath).then((resp) => resp.arrayBuffer());
  const bundle = new Int8Array(bundleBuffer);
  mark('bundle-fetch-end', { bytes: bundle.length });
  send(MESSAGES.STDERR, `bundle fetched (${bundle.length} bytes).\n`);
  send(MESSAGES.INIT);
  // init() hanging would leave the playground loading forever with no output,
  // so fail loudly instead: the parent surfaces everything sent before dying.
  const startTimeout = new Promise((resolve, reject) => {
    setTimeout(() => reject(new Error('AtomVM start timed out (VM did not boot).')), 100000);
  });
  mark('vm-init-start');
  const initProcess = await Promise.race([startVm(bundle, init), startTimeout]);
  mark('vm-init-end');

  self.addEventListener('message', async ({ data }) => {
    const type = data.type;

    if (type === MESSAGES.CALL) {
      await handleCall(data);
    } else if (type.startsWith('popcorn')) {
      send(MESSAGES.STDERR, `Worker: received unhandled popcorn event: ${JSON.stringify(data)}\n`);
    }
  });

  send(MESSAGES.START_VM, initProcess);
  mark('vm-ready');
  setInterval(() => send(MESSAGES.HEARTBEAT, null), HEARTBEAT_INTERVAL_MS);
}

async function startVm(avmBundle, init) {
  let resolveResultPromise = null;
  const resultPromise = new Promise((resolve) => {
    resolveResultPromise = resolve;
  });
  // The pinned Elixir boot bundle was built for an iframe and its JS interop
  // reads `globalThis.window.parent.document` before calling back into
  // `Module.onElixirReady`. Install the smallest possible shim after the
  // AtomVM module has been imported (so Emscripten's worker detection is not
  // affected) and before init() starts the Elixir boot process.
  globalThis.window = globalThis;
  globalThis.window.parent = globalThis;
  globalThis.window.document = globalThis.document || {};
  Module = await init({
    mainScriptUrlOrBlob: workerScript,
    locateFile: locateBinary,
    onRuntimeInitialized() {
      send(MESSAGES.STDERR, 'AtomVM wasm runtime initialized.\n');
    },
    monitorRunDependencies(left) {
      send(MESSAGES.STDERR, `AtomVM run dependencies left: ${left}\n`);
    },
    preRun: [
      function ({ FS }) {
        FS.mkdir('/data');
        FS.writeFile('/data/bundle.avm', avmBundle);
      },
    ],
    arguments: ['/data/bundle.avm'],
    print(text) {
      send(MESSAGES.STDOUT, text);
    },
    printErr(text) {
      send(MESSAGES.STDERR, text);
    },
    onAbort() {
      // Timeout so that error logs are (hopefully) printed
      // before we terminate
      setTimeout(() => send(MESSAGES.RELOAD, null), 100);
    },
  });

  Module.serialize = JSON.stringify;
  Module.deserialize = deserialize;
  Module.cleanupFunctions = new Map();
  Module.onTrackedObjectDelete = (key) => {
    const fns = Module.cleanupFunctions;
    const fn = fns.get(key);
    fns.delete(key);
    try {
      if (fn) fn();
    } catch (e) {
      send(
        MESSAGES.STDERR,
        `onTrackedObjectDelete failed: ${(e && (e.stack || e.message)) || e}\n`,
      );
    } finally {
      Module.trackedObjectsMap.delete(key);
    }
  };
  const origCast = Module.cast;
  const origCall = Module.call;

  Module.cast = (process, args) => {
    const serialized = Module.serialize(args);
    origCast(process, serialized);
  };
  Module.call = (process, args) => {
    const serialized = Module.serialize(args);
    return origCall(process, serialized);
  };

  Module.onRunTrackedJs = (scriptString, isDebug) => {
    const trackValue = (tracked) => {
      const getKey = Module.nextTrackedObjectKey;
      const map = Module.trackedObjectsMap;

      if (tracked instanceof TrackedValue) {
        map.set(tracked.key, tracked.value);
        return tracked.key;
      }

      const key = getKey();
      map.set(key, tracked);
      return key;
    };

    let fn;
    try {
      const indirectEval = eval;
      fn = indirectEval(scriptString); // NOSONAR - required by AtomVM's sandboxed JS interop
    } catch (e) {
      send(MESSAGES.STDERR, `onRunTrackedJs eval failed: ${(e && (e.stack || e.message)) || e}\n`);
      return null;
    }
    if (isDebug) ensureFunctionEval(fn);
    let result;
    try {
      result = fn(Module);
    } catch (e) {
      send(MESSAGES.STDERR, `onRunTrackedJs failed: ${(e && (e.stack || e.message)) || e}\n`);
      return null;
    }
    if (isDebug) ensureResultKeyList(result);

    return result == null ? [] : result.map(trackValue);
  };
  Module.onGetTrackedObjects = (keys) => {
    const getTrackedObject = (key) => {
      const serialize = Module.serialize;
      const map = Module.trackedObjectsMap;

      return serialize(map.get(key));
    };
    return keys.map(getTrackedObject);
  };

  Module.onElixirReady = (initProcess) => {
    Module.onElixirReady = null;
    resolveResultPromise(initProcess);
  };

  return resultPromise;
}

async function handleCall(data) {
  const { requestId, process, args } = data.value;
  send(MESSAGES.CALL_ACK, { requestId });
  mark('call-start', { requestId });

  try {
    const result = await Module.call(process, args);
    mark('call-end', { requestId });
    send(MESSAGES.CALL, { requestId, data: Module.deserialize(result) });
  } catch (error) {
    mark('call-error', { requestId, error: String(error) });
    if (error === 'noproc') {
      send(MESSAGES.RELOAD, null);
      send(MESSAGES.STDERR, 'Runtime VM crashed, worker will be restarted.\n');
      return;
    }
    send(MESSAGES.CALL, { requestId, error: Module.deserialize(error) });
  }
}

function ensureFunctionEval(maybeFunction) {
  if (typeof maybeFunction !== 'function') {
    throw new Error('Script passed to onRunTrackedJs() is not wrapped in a function');
  }
}

function ensureResultKeyList(result) {
  if (!Array.isArray(result) && result !== undefined) {
    throw new Error(
      'Script passed to onRunTrackedJs() returned invalid value, accepted values are arrays and undefined',
    );
  }
}

function send(type, data) {
  self.postMessage({ type, value: data });
}

function deserialize(message) {
  return JSON.parse(message, (key, value) => {
    const isRef =
      typeof value === 'object' &&
      value !== null &&
      Object.hasOwn(value, 'popcorn_ref') &&
      Object.getOwnPropertyNames(value).length === 1;

    if (!isRef) {
      return value;
    }
    return Module.trackedObjectsMap.get(value.popcorn_ref);
  });
}

void runWorker();
